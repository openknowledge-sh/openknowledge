import assert from 'node:assert/strict';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';

const url = new URL(process.env.OKN_EXTENSION_URL || 'http://127.0.0.1:4318/mcp');
const client = new Client({ name: 'openknowledge-live-test', version: '1' });
const transport = new StreamableHTTPClientTransport(url);
try {
  await client.connect(transport);
  const tools = await client.listTools();
  assert.equal(tools.tools.length, 6);
  assert.deepEqual(tools.tools.find(tool => tool.name === 'openknowledge_viewer_save')._meta.ui.visibility, ['app']);
  const library = await client.callTool({ name: 'openknowledge_library', arguments: {} });
  assert.ok(library.structuredContent.knowledgeBases.length > 0);
  const home = await fetch(library.structuredContent.panelURL);
  assert.equal(home.status, 200);
  const homeHTML = await home.text();
  assert.match(homeHTML, /data-file-sidebar/);
  assert.match(homeHTML, /data-knowledge-base-disclosure/);
  const base = library.structuredContent.knowledgeBases.find(base => base.alias === 'docs') || library.structuredContent.knowledgeBases[0];
  const selected = await client.callTool({ name: 'openknowledge_library', arguments: { knowledgeBase: base.alias } });
  assert.equal(selected.structuredContent.selectedKnowledgeBase, base.alias);
  assert.ok(selected.structuredContent.pages.length > 0);
  const pagePath = selected.structuredContent.pages.find(page => page.path === 'features/commands/mcp.md')?.path || selected.structuredContent.pages[0].path;
  const page = await client.callTool({ name: 'openknowledge_read_page', arguments: { knowledgeBase: base.alias, path: pagePath } });
  assert.equal(page.isError, undefined);
  assert.equal(page.structuredContent.knowledgeBase, base.alias);
  assert.ok(page.structuredContent.html.includes('<'));
  assert.ok(page.structuredContent.markdown.length > 0);
  assert.equal(Boolean(page.structuredContent.editorURL), base.access === 'write');
  const viewer = await fetch(page.structuredContent.viewerURL);
  assert.equal(viewer.status, 200);
  assert.equal(viewer.headers.get('x-frame-options'), 'DENY');
  const panel = await fetch(page.structuredContent.panelURL);
  assert.equal(panel.status, 200);
  assert.equal(panel.headers.get('x-frame-options'), null);
  assert.match(await panel.text(), /_viewer-bridge.js/);
  const search = await client.callTool({ name: 'openknowledge_search', arguments: { knowledgeBase: base.alias, query: 'MCP' } });
  assert.ok(Array.isArray(search.structuredContent.sources));
  assert.ok(search.structuredContent.sources.every(source => source.knowledgeBase === base.alias));
  const invalid = await client.callTool({ name: 'openknowledge_read_page', arguments: { knowledgeBase: base.alias, path: '../../README.md' } });
  assert.equal(invalid.isError, true);
  const resource = await client.readResource({ uri: 'ui://openknowledge/library.html' });
  assert.equal(resource.contents[0].mimeType, 'text/html;profile=mcp-app');
  assert.deepEqual(resource.contents[0]._meta.ui.csp, { connectDomains: [], resourceDomains: [], frameDomains: [] });
  assert.match(resource.contents[0].text, /openknowledge-native-viewer-bootstrap/);
  assert.match(resource.contents[0].text, /data-file-sidebar/);
  assert.ok(!resource.contents[0].text.includes('src="/assets/openknowledge/viewer.js'));
  const nativeRead = await client.callTool({ name: 'openknowledge_viewer_get', arguments: { route: new URL(page.structuredContent.viewerURL).pathname } });
  assert.equal(nativeRead.isError, undefined);
  assert.equal(nativeRead.structuredContent.status, 200);
  assert.equal(nativeRead.structuredContent.encoding, 'text');
  assert.match(nativeRead.structuredContent.body, /data-note-path/);
  const deniedSave = await client.callTool({ name: 'openknowledge_viewer_save', arguments: { route: '/api/feedback', body: '{}' } });
  assert.equal(deniedSave.isError, true);
  assert.ok(!resource.contents[0].text.includes('src="/app.js"'));
  const rejected = await fetch(url, { method: 'POST', headers: { Origin: 'https://example.com', 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal(rejected.status, 403);
  console.log(`Live MCP passed: ${library.structuredContent.knowledgeBases.length} bases; full viewer home and workspace tree; ${selected.structuredContent.pages.length} pages in ${base.alias}; native UI with no frame/network authority; app-only route transport; search attribution and traversal protection.`);
} finally { await transport.terminateSession().catch(() => {}); await client.close(); }
